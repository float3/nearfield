#!/usr/bin/env python3
"""Add the permissions Tauri's generated AndroidManifest does not carry.

`app/src-tauri/gen/` is regenerated by `tauri android init` on every build, so
anything added to the manifest has to be re-applied each time — the same
reason `inject-signing.py` exists. Idempotent.

Currently one entry: REQUEST_INSTALL_PACKAGES, without which starting the
package installer from inside the app is refused on Android 8 and later. The
FileProvider the installer needs is already declared by Tauri's own Android
library, over the cache directory, which is why the update lands there.

Usage: inject-manifest.py <path-to-AndroidManifest.xml>
"""

import sys
from pathlib import Path

PERMISSIONS = [
    "android.permission.REQUEST_INSTALL_PACKAGES",
]


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    path = Path(sys.argv[1])
    if not path.exists():
        print(f"not found: {path} — run `tauri android init` first", file=sys.stderr)
        return 1

    src = path.read_text(encoding="utf8")
    added = []
    for perm in PERMISSIONS:
        if perm in src:
            continue
        line = f'    <uses-permission android:name="{perm}" />\n'
        marker = "    <application"
        if marker not in src:
            print("unexpected manifest: no <application> element", file=sys.stderr)
            return 1
        src = src.replace(marker, line + marker, 1)
        added.append(perm)

    if not added:
        print("manifest already has every permission it needs")
        return 0

    path.write_text(src, encoding="utf8")
    for perm in added:
        print(f"added {perm}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
