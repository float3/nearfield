#!/usr/bin/env python3
"""Add what Tauri's generated AndroidManifest does not carry for updating in place.

`app/src-tauri/gen/` is regenerated by `tauri android init` on every build, so
anything added to the manifest has to be re-applied each time — the same
reason `inject-signing.py` exists. Idempotent.

Two entries:

- REQUEST_INSTALL_PACKAGES, without which starting the package installer from
  inside the app is refused on Android 8 and later.
- A FileProvider over the cache's `updates/` folder, authority
  `<applicationId>.fileprovider`, which is how the installer is handed the
  downloaded APK: Android refuses a `file://` URI. Tauri's Android library
  declares no provider of its own, so without this one `getUriForFile` fails.

Usage: inject-manifest.py <path-to-AndroidManifest.xml>
"""

import sys
from pathlib import Path

PERMISSIONS = [
    "android.permission.REQUEST_INSTALL_PACKAGES",
]

PATHS_NAME = "nearfield_file_paths"

PROVIDER = f"""        <provider
            android:name="androidx.core.content.FileProvider"
            android:authorities="${{applicationId}}.fileprovider"
            android:exported="false"
            android:grantUriPermissions="true">
            <meta-data
                android:name="android.support.FILE_PROVIDER_PATHS"
                android:resource="@xml/{PATHS_NAME}" />
        </provider>
"""

PATHS = """<?xml version="1.0" encoding="utf-8"?>
<paths>
    <cache-path name="updates" path="updates/" />
</paths>
"""


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    path = Path(sys.argv[1])
    if not path.exists():
        print(f"not found: {path} — run `tauri android init` first", file=sys.stderr)
        return 1

    src = path.read_text(encoding="utf8")
    if "    <application" not in src or "</application>" not in src:
        print("unexpected manifest: no <application> element", file=sys.stderr)
        return 1

    added = []
    for perm in PERMISSIONS:
        if perm in src:
            continue
        line = f'    <uses-permission android:name="{perm}" />\n'
        src = src.replace("    <application", line + "    <application", 1)
        added.append(perm)

    if "androidx.core.content.FileProvider" not in src:
        src = src.replace("    </application>", PROVIDER + "    </application>", 1)
        if "androidx.core.content.FileProvider" not in src:
            src = src.replace("</application>", PROVIDER + "</application>", 1)
        added.append("FileProvider")

    paths = path.parent / "res" / "xml" / f"{PATHS_NAME}.xml"
    if not paths.exists() or paths.read_text(encoding="utf8") != PATHS:
        paths.parent.mkdir(parents=True, exist_ok=True)
        paths.write_text(PATHS, encoding="utf8")
        added.append(f"res/xml/{PATHS_NAME}.xml")

    if not added:
        print("manifest already has everything it needs")
        return 0

    path.write_text(src, encoding="utf8")
    for item in added:
        print(f"added {item}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
